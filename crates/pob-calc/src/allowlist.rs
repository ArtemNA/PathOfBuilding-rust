//! Which `stats` keys the oracle candidate may claim (R4-ARCH gate (b), CALC-ARCH §9; pob-ts `src/api/allowlist.ts`).
//!
//! The lists are MEASURED, not chosen: a key is in [`ALLOWLIST`] iff its value is `ok` (round4, O3) against
//! `pob-ts/tools/oracle/goldens/*.json` on EVERY one of the six golden builds that produces it, and is never `extra`.
//! `tests/allowlist.rs` re-derives exactly that through `pob_golden::compare_stats`, so a key that starts or stops matching
//! fails there. [`EXCLUDED`] is the other half: every key the engine writes that failed the measurement, with the gap
//! that explains it (root causes: `item-miss`, `cluster`, `tree-jewel`, `gems`, `skills`, `reservation`, `guards`,
//! `buffs`, `curses`, `flasks`, `ailments` -- the pob-ts `ROOT_CAUSES` vocabulary). The two are disjoint and together
//! cover every key Rust emits on any golden.
//!
//! The point of the filter is honesty: an unfiltered candidate would report a wrong number as a number, a filtered one
//! reports nothing and the harness counts the key as `unimplemented` (the progress metric). `POB_EXPERIMENTAL=1` in
//! `pob-cli` turns the filter off.
//!
//! Reasons are the root causes pob-ts established for the same keys (the measurement here proves only ok/mismatch);
//! the sets themselves were measured on this engine and are identical to pob-ts.

use indexmap::IndexMap;

use crate::output::StatValue;

/// pob-ts `ROOT_CAUSES`: every `EXCLUDED` reason names at least one of these literally.
pub const ROOT_CAUSES: [&str; 11] = [
    "item-miss",
    "cluster",
    "tree-jewel",
    "gems",
    "skills",
    "reservation",
    "guards",
    "buffs",
    "curses",
    "flasks",
    "ailments",
];

/// The root causes a reason names, in `ROOT_CAUSES` order.
pub fn root_causes(reason: &str) -> Vec<&'static str> {
    ROOT_CAUSES.iter().copied().filter(|c| reason.contains(c)).collect()
}

/// `true` iff the key is measured-correct on all six goldens.
pub fn is_allowed(key: &str) -> bool {
    ALLOWLIST.binary_search(&key).is_ok()
}

/// `stats` restricted to [`ALLOWLIST`], order kept (pob-ts `candidate.ts`).
pub fn filter_stats(stats: &IndexMap<String, StatValue>) -> IndexMap<String, StatValue> {
    stats
        .iter()
        .filter(|(k, _)| is_allowed(k))
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect()
}

